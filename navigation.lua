function N.inside(poly,x,y)
 local result=false
 local j=#poly
 for i=1,#poly do
  local a,b=poly[i],poly[j]
  if (a[2]>y)~=(b[2]>y) and x<(b[1]-a[1])*(y-a[2])/(b[2]-a[2])+a[1] then result=not result end
  j=i
 end
 return result
end
function N.walkable(room,x,y)
 local r=N.rooms[room];if not r then return false end
 local onFloor=false
 for _,p in ipairs(r.floor)do if N.inside(p,x,y)then onFloor=true;break end end
 if not onFloor then return false end
 for _,p in ipairs(r.solid)do if N.inside(p,x,y)then return false end end
 return true
end
return N
